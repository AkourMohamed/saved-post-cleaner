/**
 * Saved Post Cleaner — internationalization
 *
 * Loaded as a plain script (no bundler/build step) by the content script,
 * the options page and the popup, exactly like config.js — so the message
 * catalogs and the locale-resolution logic live in one place instead of
 * being duplicated per context.
 *
 * SCOPE: this translates *this extension's own* interface — the on-page
 * panel, the toolbar popup, and the settings page. It deliberately does
 * not touch how the automation finds Instagram's controls; those
 * selectors (UNSAVE_LABEL_PATTERN and friends in content.js) still match
 * Instagram's English wording only. See "Language support" in the README
 * for what that means in practice.
 *
 * Adding a language: append an entry to IGSC_LANGUAGES and a block to
 * IGSC_MESSAGES. Nothing else needs touching — the options page builds
 * its dropdown from IGSC_LANGUAGES, and any key a new block omits falls
 * back to English rather than rendering blank.
 */

