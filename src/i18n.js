// Turns a BCP-47 tag into one of our catalog codes, or null.
// Tries the full tag first ("pt-BR"), then the base language ("pt"),
// so a browser reporting "pt-BR" or "fr-CA" still lands on pt / fr.
function igscNormalizeLocale(tag) {
  if (!tag) return null;
  const lower = String(tag).toLowerCase().replace(/_/g, '-');
  if (IGSC_MESSAGES[lower]) return lower;
  const base = lower.split('-')[0];
  if (IGSC_MESSAGES[base]) return base;
  return null;
}

// Resolves the setting ('auto' or a language code) to a catalog code.
// 'auto' walks the browser's full preference list rather than just
// navigator.language, so someone whose first choice we don't ship still
// gets their second choice instead of dropping straight to English.
function igscResolveLocale(setting) {
  if (setting && setting !== 'auto') {
    const explicit = igscNormalizeLocale(setting);
    if (explicit) return explicit;
  }
  const preferences = []
    .concat(typeof navigator !== 'undefined' && navigator.languages ? Array.from(navigator.languages) : [])
    .concat(typeof navigator !== 'undefined' && navigator.language ? [navigator.language] : []);
  for (const tag of preferences) {
    const match = igscNormalizeLocale(tag);
    if (match) return match;
  }
  return IGSC_DEFAULT_LOCALE;
}

function igscDirFor(locale) {
  const entry = IGSC_LANGUAGES.find((lang) => lang.code === locale);
  return entry && entry.dir ? entry.dir : 'ltr';
}

// Builds a translate function bound to one locale. Missing keys fall back
// to English and then to the key name itself, so a typo shows up as a
// visible key rather than a silently blank element.
function igscMakeT(locale) {
  const catalog = IGSC_MESSAGES[locale] || IGSC_MESSAGES[IGSC_DEFAULT_LOCALE];
  const fallback = IGSC_MESSAGES[IGSC_DEFAULT_LOCALE];
  return function t(key, params) {
    let text = catalog[key];
    if (text === undefined) text = fallback[key];
    if (text === undefined) return key;
    if (params) {
      for (const name of Object.keys(params)) {
        text = text.split('{' + name + '}').join(String(params[name]));
      }
    }
    return text;
  };
}

