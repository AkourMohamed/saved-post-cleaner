// Compiles one field of the table into a single case-insensitive regex.
// Callers build these once, not per post — this feeds a loop that runs
// over hundreds of tiles.
function igscBuildLabelPattern(field, codes) {
  const sources = [];
  const wanted = codes || Object.keys(IGSC_IG_LABELS);
  for (const code of wanted) {
    const entry = IGSC_IG_LABELS[code];
    if (entry && entry[field]) sources.push.apply(sources, entry[field]);
  }
  if (sources.length === 0) return null;
  return new RegExp(sources.join('|'), 'i');
}

// Which language Instagram itself is rendering in, taken from the <html
// lang> attribute it sets. Trying that language's wording *first* means
// the precise match wins over the catch-all union, so we never have to
// disambiguate between two languages that happen to share a word.
// Returns null when the page doesn't say, or names a language we have no
// wording for — both of which simply fall through to the union.
function igscPageLanguageCode(langAttr) {
  if (!langAttr) return null;
  const lower = String(langAttr).toLowerCase().replace(/_/g, '-');
  if (IGSC_IG_LABELS[lower]) return lower;
  const base = lower.split('-')[0];
  if (IGSC_IG_LABELS[base]) return base;
  if (base === 'no' || base === 'nn') return 'nb';
  if (base === 'in') return 'id'; // legacy code some browsers still send
  return null;
}
